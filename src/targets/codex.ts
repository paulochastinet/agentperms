export const CODEX_PROFILE = 'agentperms';
const DECISION: Record<Decision, string> = { allow: 'allow', ask: 'prompt', deny: 'forbidden' };

function codexDir(scope: Scope, ctx: Ctx): string {
  return scope === 'project' ? path.join(ctx.cwd, '.codex') : path.join(ctx.home, '.codex');
}
export function codexRulesFile(scope: Scope, ctx: Ctx): string {
  return path.join(codexDir(scope, ctx), 'rules', 'agentperms.rules');
}
export function codexConfigFile(scope: Scope, ctx: Ctx): string {
  return path.join(codexDir(scope, ctx), 'config.toml');
}

/** Policy shell pattern -> Codex prefix_rule token list (Codex matches argv prefixes only). */
export function codexPrefix(pattern: string, d: Decision): { tokens: string[] | null; note?: string; level?: 'info' | 'warn' } {
  const p = parseShellPattern(pattern);
  if (p.text === '*') {
    return d === 'allow'
      ? { tokens: null, note: 'Codex rules need a program name; "allow everything" is not mapped', level: 'info' }
      : { tokens: null, note: 'Codex rules need a program name; this rule is NOT enforced in Codex', level: 'warn' };
  }
  if (p.trailing) return { tokens: p.literalTokens };
  if (p.exact) {
    if (d === 'allow')
      return {
        tokens: null,
        note: `Codex rules match prefixes, so allowing exactly "${p.text}" would also allow "${p.text} <any args>"; not mapped (write "${p.text} *" if any arguments are fine)`,
        level: 'info',
      };
    return { tokens: p.tokens, note: `${d} applies to "${p.text}" with any extra arguments (Codex matches prefixes; stricter)`, level: 'info' };
  }
  // inner wildcard
  if (d === 'allow') return { tokens: null, note: 'Codex rules cannot express a wildcard in the middle of a command; not mapped', level: 'info' };
  if (!p.literalTokens.length) return { tokens: null, note: 'wildcard before the program name; this rule is NOT enforced in Codex', level: 'warn' };
  return {
    tokens: p.literalTokens,
    note: `Codex rules cannot express a wildcard in the middle; ${d} broadened to every "${p.literalTokens.join(' ')} ..." command (stricter)`,
    level: 'info',
  };
}

export function codexRulesContent(policy: Policy, warnings: MappingWarning[]): string | null {
  const blocks: string[] = [];
  const seen = new Set<string>();
  for (const d of ['deny', 'ask', 'allow'] as Decision[]) {
    for (const s of policy.shell[d]) {
      const r = codexPrefix(s, d);
      if (r.note) warnings.push(warn('codex', r.level ?? 'info', `shell.${d} "${s}": ${r.note}`));
      if (!r.tokens || !r.tokens.length) continue;
      const key = `${d}:${r.tokens.join('\u0000')}`;
      if (seen.has(key)) continue;
      seen.add(key);
      blocks.push(
        [
          'prefix_rule(',
          `    pattern = [${r.tokens.map(tomlString).join(', ')}],`,
          `    decision = ${tomlString(DECISION[d])},`,
          `    justification = ${tomlString(`agentperms: shell.${d} "${s}"`)},`,
          ')',
        ].join('\n'),
      );
    }
  }
  if (!blocks.length) return null;
  return (
    [
      `# ${MANAGED_HEADER} (https://github.com/paulochastinet/agentperms).`,
      '# Do not edit: this file is regenerated by `agentperms apply`. Edit agentperms.yaml instead.',
      '# Codex applies the most restrictive matching rule: forbidden > prompt > allow.',
      '',
      blocks.join('\n\n'),
    ].join('\n') + '\n'
  );
}

/** File rules -> a Codex permission profile (inactive until selected with default_permissions). */
export function codexProfileBlock(policy: Policy, warnings: MappingWarning[]): string | null {
  const W = (level: 'info' | 'warn', m: string) => warnings.push(warn('codex', level, m));
  const ws = new Map<string, 'deny' | 'read'>();
  const abs = new Map<string, 'deny' | 'read'>();
  const put = (p: string, v: 'deny' | 'read') => {
    let key = p.startsWith('./') ? p.slice(2) : p;
    const table = key.startsWith('/') || key.startsWith('~') ? abs : ws;
    if (table === ws && isAnyDepth(key) && !key.startsWith('**/')) key = `**/${key}`;
    if (key.endsWith('/')) key += '**';
    const prev = table.get(key);
    if (prev === 'deny') return;
    table.set(key, v);
  };
  for (const p of policy.files.read.deny) put(p, 'deny');
  for (const p of policy.files.write.deny) put(p, 'read');
  for (const p of policy.files.read.ask) {
    put(p, 'deny');
    W('info', `files.read.ask "${p}": Codex has no per-path prompt; mapped to deny in the permission profile (stricter)`);
  }
  for (const p of policy.files.write.ask) {
    put(p, 'read');
    W('info', `files.write.ask "${p}": Codex has no per-path prompt; mapped to read-only in the permission profile (stricter)`);
  }
  if (policy.files.read.allow.length || policy.files.write.allow.length)
    W('info', 'files.*.allow: not mapped for Codex; its sandbox decides what is readable/writable (allows are never widened)');
  if (policy.web.allow.length || policy.web.ask.length || policy.web.deny.length)
    W('info', 'web: not mapped for Codex; network access is controlled by the sandbox (network off by default in workspace-write)');
  if (policy.mcp.deny.length)
    W('warn', `mcp.deny: NOT enforced in Codex by agentperms; use enabled_tools / disabled_tools under [mcp_servers.<id>] in config.toml (${policy.mcp.deny.join(', ')})`);
  else if (policy.mcp.allow.length || policy.mcp.ask.length)
    W('info', 'mcp: not mapped for Codex; per-tool approval lives in [mcp_servers.<id>.tools.<tool>] approval_mode');
  if (!ws.size && !abs.size) return null;

  const lines = [
    BLOCK_BEGIN,
    `# Permission profile generated from files.read / files.write. It is NOT active until you set`,
    `# default_permissions = "${CODEX_PROFILE}" (which replaces sandbox_mode / [sandbox_workspace_write]).`,
    `[permissions.${CODEX_PROFILE}]`,
    'extends = ":workspace"',
  ];
  if (abs.size) {
    lines.push('', `[permissions.${CODEX_PROFILE}.filesystem]`);
    for (const [k, v] of abs) lines.push(`${tomlString(k)} = ${tomlString(v)}`);
  }
  if (ws.size) {
    lines.push('', `[permissions.${CODEX_PROFILE}.filesystem.":workspace_roots"]`);
    for (const [k, v] of ws) lines.push(`${tomlString(k)} = ${tomlString(v)}`);
  }
  lines.push(BLOCK_END);
  W(
    'warn',
    `files: written as the Codex permission profile "${CODEX_PROFILE}" in config.toml, which is inactive until you set default_permissions = "${CODEX_PROFILE}" (agentperms does not switch your sandbox for you)`,
  );
  return lines.join('\n');
}

