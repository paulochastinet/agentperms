interface ParsedPrefixRule {
  patterns: string[][];
  decision: string;
}

/** Remove `#` comments that are outside of string literals. */
function stripComments(text: string): string {
  let out = '';
  let q: string | null = null;
  for (let i = 0; i < text.length; i++) {
    const c = text[i]!;
    if (q) {
      out += c;
      if (c === '\\') out += text[++i] ?? '';
      else if (c === q) q = null;
    } else if (c === '"' || c === "'") {
      q = c;
      out += c;
    } else if (c === '#') {
      while (i < text.length && text[i] !== '\n') i++;
      out += '\n';
    } else out += c;
  }
  return out;
}

/** Tiny Starlark-subset parser for `prefix_rule(...)` calls. */
export function parseCodexRules(text: string): ParsedPrefixRule[] {
  const out: ParsedPrefixRule[] = [];
  const src = stripComments(text);
  const re = /\bprefix_rule\s*\(/g;
  let m: RegExpExecArray | null;
  while ((m = re.exec(src))) {
    let i = m.index + m[0].length;
    let depth = 1;
    let q: string | null = null;
    for (; i < src.length && depth > 0; i++) {
      const c = src[i];
      if (q) {
        if (c === '\\') i++;
        else if (c === q) q = null;
        continue;
      }
      if (c === '"' || c === "'") q = c;
      else if (c === '(' || c === '[') depth++;
      else if (c === ')' || c === ']') depth--;
    }
    const body = src.slice(m.index + m[0].length, i - 1);
    const value = (name: string): string | undefined => {
      const r = new RegExp(`\\b${name}\\s*=\\s*`).exec(body);
      if (!r) return undefined;
      let j = r.index + r[0].length;
      const start = j;
      let d = 0;
      let qq: string | null = null;
      for (; j < body.length; j++) {
        const c = body[j];
        if (qq) {
          if (c === '\\') j++;
          else if (c === qq) qq = null;
          continue;
        }
        if (c === '"' || c === "'") qq = c;
        else if (c === '[' || c === '(') d++;
        else if (c === ']' || c === ')') d--;
        else if (c === ',' && d === 0) break;
      }
      return body.slice(start, j).trim();
    };
    const pat = value('pattern');
    const dec = value('decision');
    const decision = dec ? (strLit(dec) ?? 'allow') : 'allow';
    const patterns = pat ? expandPattern(pat) : [];
    if (patterns.length) out.push({ patterns, decision });
  }
  return out;
}

function strLit(s: string): string | undefined {
  const t = s.trim();
  if (/^"(?:[^"\\]|\\.)*"$/.test(t)) {
    try {
      return JSON.parse(t) as string;
    } catch {
      return t.slice(1, -1);
    }
  }
  if (/^'(?:[^'\\]|\\.)*'$/.test(t)) return t.slice(1, -1).replace(/\\'/g, "'");
  return undefined;
}

/** `["git", ["status", "diff"]]` -> [["git","status"],["git","diff"]] (capped). */
function expandPattern(src: string): string[][] {
  const tokens: (string | string[])[] = [];
  const inner = src.trim().replace(/^\[/, '').replace(/\]$/, '');
  const re = /\[((?:[^\]"']|"(?:[^"\\]|\\.)*"|'(?:[^'\\]|\\.)*')*)\]|("(?:[^"\\]|\\.)*"|'(?:[^'\\]|\\.)*')/g;
  let m: RegExpExecArray | null;
  while ((m = re.exec(inner))) {
    if (m[1] !== undefined) {
      const alts = [...m[1].matchAll(/"(?:[^"\\]|\\.)*"|'(?:[^'\\]|\\.)*'/g)].map((x) => strLit(x[0]) ?? '');
      tokens.push(alts);
    } else if (m[2]) tokens.push(strLit(m[2]) ?? '');
  }
  let combos: string[][] = [[]];
  for (const t of tokens) {
    const alts = Array.isArray(t) ? t : [t];
    combos = combos.flatMap((c) => alts.map((a) => [...c, a])).slice(0, 64);
  }
  return combos.filter((c) => c.length);
}

const D_FROM_CODEX: Record<string, Decision> = { allow: 'allow', prompt: 'ask', forbidden: 'deny' };

function listRules(dir: string): string[] {
  try {
    return readdirSync(dir)
      .filter((f) => f.endsWith('.rules'))
      .sort()
      .map((f) => path.join(dir, f));
  } catch {
    return [];
  }
}

function readConfig(file: string, scope: 'project' | 'user', snap: AgentSnapshot) {
  if (snap.files.some((f) => f.path === file)) return;
  const { text, error } = readText(file);
  const src: SourceFile = { path: file, scope, exists: text !== null };
  if (error) src.error = error;
  snap.files.push(src);
  if (text === null) return;
  let cfg: Record<string, unknown>;
  try {
    cfg = parseToml(text) as Record<string, unknown>;
  } catch {
    src.error = 'invalid TOML';
    return;
  }
  const set = (key: string, value: unknown) => {
    if (value === undefined || value === null || typeof value === 'object') return;
    snap.settings.push({ agent: 'codex', scope, file, key, value: String(value) });
  };
  set('approval_policy', typeof cfg.approval_policy === 'object' ? 'granular' : cfg.approval_policy);
  set('sandbox_mode', cfg.sandbox_mode);
  set('default_permissions', cfg.default_permissions);
  const sww = cfg.sandbox_workspace_write as Record<string, unknown> | undefined;
  if (sww) set('sandbox_workspace_write.network_access', sww.network_access);
  const profiles = cfg.profiles as Record<string, Record<string, unknown>> | undefined;
  for (const [name, p] of Object.entries(profiles ?? {})) {
    if (!p || typeof p !== 'object') continue;
    set(`profiles.${name}.approval_policy`, typeof p.approval_policy === 'object' ? 'granular' : p.approval_policy);
    set(`profiles.${name}.sandbox_mode`, p.sandbox_mode);
  }
  const perms = cfg.permissions as Record<string, Record<string, unknown>> | undefined;
  for (const [name, prof] of Object.entries(perms ?? {})) {
    if (!prof || typeof prof !== 'object') continue;
    const fsys = prof.filesystem as Record<string, unknown> | undefined;
    const walk = (obj: Record<string, unknown> | undefined) => {
      for (const [k, v] of Object.entries(obj ?? {})) {
        if (v && typeof v === 'object') walk(v as Record<string, unknown>);
        else if (v === 'deny') snap.rules.push({ agent: 'codex', scope, file, category: 'read', decision: 'deny', pattern: k, native: `[permissions.${name}] ${k} = "deny"` });
        else if (v === 'read') snap.rules.push({ agent: 'codex', scope, file, category: 'write', decision: 'deny', pattern: k, native: `[permissions.${name}] ${k} = "read"` });
      }
    };
    walk(fsys);
    const net = prof.network as Record<string, unknown> | undefined;
    if (net) set(`permissions.${name}.network.enabled`, net.enabled);
    for (const [dom, v] of Object.entries((net?.domains as Record<string, unknown>) ?? {})) {
      if (v === 'allow' || v === 'deny')
        snap.rules.push({ agent: 'codex', scope, file, category: 'web', decision: v, pattern: dom, native: `[permissions.${name}.network.domains] "${dom}" = "${v}"` });
    }
  }
  const mcp = cfg.mcp_servers as Record<string, Record<string, unknown>> | undefined;
  for (const [server, conf] of Object.entries(mcp ?? {})) {
    if (!conf || typeof conf !== 'object') continue;
    if (conf.default_tools_approval_mode === 'auto' || conf.default_tools_approval_mode === 'approve')
      snap.rules.push({ agent: 'codex', scope, file, category: 'mcp', decision: 'allow', pattern: `${server}:*`, native: `[mcp_servers.${server}] default_tools_approval_mode = "${String(conf.default_tools_approval_mode)}"` });
    for (const t of Array.isArray(conf.disabled_tools) ? conf.disabled_tools : [])
      if (typeof t === 'string') snap.rules.push({ agent: 'codex', scope, file, category: 'mcp', decision: 'deny', pattern: `${server}:${t}`, native: `[mcp_servers.${server}] disabled_tools "${t}"` });
    const tools = conf.tools as Record<string, Record<string, unknown>> | undefined;
    for (const [t, tc] of Object.entries(tools ?? {})) {
      const mode = tc?.approval_mode;
      if (mode === 'auto' || mode === 'approve')
        snap.rules.push({ agent: 'codex', scope, file, category: 'mcp', decision: 'allow', pattern: `${server}:${t}`, native: `[mcp_servers.${server}.tools.${t}] approval_mode = "${String(mode)}"` });
    }
  }
  if (scope === 'user') {
    const projects = cfg.projects as Record<string, Record<string, unknown>> | undefined;
    const trusted = Object.values(projects ?? {}).filter((p) => p?.trust_level === 'trusted').length;
    if (trusted) set('projects.trusted', String(trusted));
  }
}

function readRulesDir(dir: string, scope: 'project' | 'user', snap: AgentSnapshot) {
  for (const file of listRules(dir)) {
    if (snap.files.some((f) => f.path === file)) continue;
    const { text, error } = readText(file);
    const src: SourceFile = { path: file, scope, exists: text !== null };
    if (error) src.error = error;
    snap.files.push(src);
    if (text === null) continue;
    for (const r of parseCodexRules(text)) {
      const decision = D_FROM_CODEX[r.decision] ?? 'allow';
      for (const toks of r.patterns) {
        const pattern = `${toks.join(' ')} *`;
        snap.rules.push({ agent: 'codex', scope, file, category: 'shell', decision, pattern, native: `prefix_rule(${JSON.stringify(toks)}, ${r.decision})` });
      }
    }
  }
}

export const codex: Target = {
  id: 'codex',
  name: 'Codex CLI',
  files: (scope, ctx) => [codexRulesFile(scope, ctx), codexConfigFile(scope, ctx)],
  generate(policy, scope, ctx): TargetOutput {
    const warnings: MappingWarning[] = [];
    const rules = codexRulesContent(policy, warnings);
    const block = codexProfileBlock(policy, warnings);
    if (scope === 'project')
      warnings.push(warn('codex', 'info', 'project .codex/ rules and config are only loaded when the project is trusted in Codex'));
    return {
      target: 'codex',
      scope,
      warnings,
      files: [
        { kind: 'owned', file: codexRulesFile(scope, ctx), content: rules, comment: '#' },
        { kind: 'toml-block', file: codexConfigFile(scope, ctx), block },
      ],
    };
  },
  read(ctx, scopes): AgentSnapshot {
    const snap: AgentSnapshot = { agent: 'codex', detected: false, files: [], rules: [], settings: [] };
    for (const scope of ['user', 'project'] as const) {
      if (!scopes.includes(scope)) continue;
      const dir = codexDir(scope, ctx);
      readConfig(path.join(dir, 'config.toml'), scope, snap);
      readRulesDir(path.join(dir, 'rules'), scope, snap);
    }
    snap.detected =
      snap.files.some((f) => f.exists) ||
      (scopes.includes('user') && dirExists(path.join(ctx.home, '.codex'))) ||
      (scopes.includes('project') && dirExists(path.join(ctx.cwd, '.codex')));
    return snap;
  },
};
